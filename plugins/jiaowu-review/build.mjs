#!/usr/bin/env node
// Builds the single-file page entry and, with --zip, the upload package.
//
//   node build.mjs          writes ui/main.js
//   node build.mjs --check  fails if ui/main.js is out of date
//   node build.mjs --zip    also writes dist/jiaowu-review-<version>.zip
//
// A surface is one script with no module graph, so lib/protocol.mjs and
// ui/view.mjs are inlined into ui/page.mjs. Both only have top-level
// `export const` / `export function` plus imports of each other, which keeps
// this a text transform.

import { execFileSync } from "node:child_process";
import { mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = dirname(fileURLToPath(import.meta.url));
const read = (path) => readFileSync(join(root, path), "utf8");

function stripImports(source) {
  return source.replace(/^import \{[^}]*\} from "[^"]+";\n/gm, "");
}

export function buildPage() {
  const inline = (path) => stripImports(read(path)).replace(/^export (const|function) /gm, "$1 ");
  const protocol = inline("lib/protocol.mjs");
  const view = inline("ui/view.mjs");
  const page = stripImports(read("ui/page.mjs"));
  if (/^\s*(import|export)\s/m.test(protocol + view + page)) throw new Error("module syntax left in the page bundle");
  return [
    "// Generated by build.mjs from ui/page.mjs, ui/view.mjs and lib/protocol.mjs. Do not edit.",
    "(() => {",
    '"use strict";',
    protocol,
    view,
    page,
    "})();",
    "",
  ].join("\n");
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const output = buildPage();
  const target = join(root, "ui/main.js");
  if (process.argv.includes("--check")) {
    if (readFileSync(target, "utf8") !== output) {
      console.error("ui/main.js is out of date; run node build.mjs");
      process.exit(1);
    }
  } else {
    writeFileSync(target, output);
  }
  if (process.argv.includes("--zip")) {
    const { version } = JSON.parse(read("multica.plugin.json"));
    const dist = join(root, "dist");
    const archive = join(dist, `jiaowu-review-${version}.zip`);
    mkdirSync(dist, { recursive: true });
    rmSync(archive, { force: true });
    execFileSync("zip", ["-X", "-q", archive, "multica.plugin.json", "ui/main.js"], { cwd: root });
    console.log(archive);
  }
}
